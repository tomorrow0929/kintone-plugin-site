/**
 * 文中の [表示する文字](キー) を、文字とリンクの並びに分ける。
 * React 側と静的HTML側の両方で使う。
 *
 * 返り値の例:
 *   ['詳しくは', { label: 'プライバシーポリシー', href: 'https://…', external: true }, 'をご覧ください。']
 */
export function splitLinks(text, links) {
  const parts = []
  const pattern = /\[([^\]]+)\]\(([^)]+)\)/g
  let last = 0
  for (const match of text.matchAll(pattern)) {
    if (match.index > last) parts.push(text.slice(last, match.index))
    const [, label, key] = match
    const internal = key.startsWith('/')
    const href = internal ? key : links[key]
    if (!href) {
      // キーの書き間違い。リンクにせず文字だけ出す（ページは壊さない）
      parts.push(label)
    } else {
      parts.push({ label, href, external: !internal })
    }
    last = match.index + match[0].length
  }
  if (last < text.length) parts.push(text.slice(last))
  return parts
}
